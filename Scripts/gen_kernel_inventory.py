#!/usr/bin/env python3
"""Generate the runtime kernel inventory from its shared JSON manifest."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "Scripts" / "kernel_inventory.json"
OUTPUT = ROOT / "Sources" / "Runtime" / "QWEngine" / "Module" / "QWKernelInventory.swift"
GROUPS = ("common", "standard_only", "dense_only", "flash_only", "moe_only")


def load_manifest():
    inventory = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if set(inventory) != set(GROUPS):
        raise ValueError(f"kernel inventory must contain exactly {GROUPS}")
    for group in GROUPS:
        names = inventory[group]
        if not isinstance(names, list) or any(not isinstance(name, str) or not name.startswith("qwg_") for name in names):
            raise ValueError(f"invalid kernel names in {group}")
        if len(set(names)) != len(names):
            raise ValueError(f"duplicate kernel names in {group}")
    for groups in (("common", "standard_only", "dense_only"),
                   ("common", "flash_only"), ("common", "standard_only", "moe_only")):
        names = [name for group in groups for name in inventory[group]]
        if len(names) != len(set(names)):
            raise ValueError(f"duplicate kernel names across {groups}")
    return inventory


def render(inventory):
    lines = ["// Generated by Scripts/gen_kernel_inventory.py; edit Scripts/kernel_inventory.json.",
             "enum QWKernelInventory {"]
    for group in GROUPS:
        lines.append(f"    static let {group}: [String] = [")
        lines.extend(f'        "{name}",' for name in inventory[group])
        lines.append("    ]")
    lines.extend(["    static let standard = common + standard_only",
                  "    static let dense = standard + dense_only",
                  "    static let flash = common + flash_only",
                  "    static let moe = standard + moe_only",
                  "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(load_manifest())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"stale kernel inventory: run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
