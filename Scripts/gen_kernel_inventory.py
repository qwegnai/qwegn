#!/usr/bin/env python3
"""Generate the runtime kernel inventory from its shared JSON manifest."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "Scripts" / "kernel_inventory.json"
OUTPUT = ROOT / "Sources" / "Runtime" / "QWEngine" / "Module" / "QWKernelInventory.swift"
NAX_MANIFEST = ROOT / "Scripts" / "nax_kernels.json"
NAX_OUTPUT = ROOT / "Sources" / "Foundation" / "QWHAL" / "QWNaxKernelRegistry.swift"
GROUPS = ("common", "dense_only", "hyper_only", "inkling2_only")


def load_manifest():
    inventory = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if set(inventory) != set(GROUPS):
        raise ValueError(f"kernel inventory must contain exactly {GROUPS}")
    for group in GROUPS:
        names = inventory[group]
        if not isinstance(names, list) or any(not isinstance(name, str) or not name.startswith("qwg_") for name in names):
            raise ValueError(f"invalid kernel names in {group}")
        if len(set(names)) != len(names):
            raise ValueError(f"duplicate kernel names in {group}")
    all_names = [name for group in GROUPS for name in inventory[group]]
    if len(all_names) != len(set(all_names)):
        raise ValueError("duplicate kernel names across inventory groups")
    return inventory


def load_nax_manifest():
    names = json.loads(NAX_MANIFEST.read_text(encoding="utf-8"))
    if not isinstance(names, list) or any(not isinstance(n, str) or not n.startswith("qwg_") for n in names):
        raise ValueError("nax_kernels.json must be a list of kernel names")
    if len(set(names)) != len(names):
        raise ValueError("duplicate kernel names in nax_kernels.json")
    return sorted(names)


def render_nax_registry(names):
    lines = [
        "// QWNaxKernelRegistry.swift — Apple10+ NAX tensor kernel names.",
        "// Generated by Scripts/gen_kernel_inventory.py; edit Scripts/nax_kernels.json.",
        "",
        "public enum QWNaxKernelRegistry {",
        "    public static let names: Set<String> = [",
    ]
    lines.extend(f'        "{name}",' for name in names)
    lines.extend(["    ]", "}", ""])
    return "\n".join(lines)


def render(inventory):
    lines = ["// Generated by Scripts/gen_kernel_inventory.py; edit Scripts/kernel_inventory.json.",
             "enum QWKernelInventory {"]
    for group in GROUPS:
        lines.append(f"    static let {group}: [String] = [")
        lines.extend(f'        "{name}",' for name in inventory[group])
        lines.append("    ]")
    lines.extend(["    static let dense = common + dense_only",
                  "    static let flash = common + hyper_only",
                  "    static let inkling2 = inkling2_only",
                  "    static let all = common + dense_only + hyper_only + inkling2_only",
                  "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(load_manifest())
    generated_nax = render_nax_registry(load_nax_manifest())
    if args.check:
        stale = False
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"stale kernel inventory: run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            stale = True
        if not NAX_OUTPUT.exists() or NAX_OUTPUT.read_text(encoding="utf-8") != generated_nax:
            print(f"stale NAX registry: run python3 {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            stale = True
        return 1 if stale else 0
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
        NAX_OUTPUT.write_text(generated_nax, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
